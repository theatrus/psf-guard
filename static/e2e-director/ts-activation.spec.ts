import { expect, test } from '@playwright/test';
import Database from 'better-sqlite3';
import { randomUUID } from 'node:crypto';
import { mkdtempSync } from 'node:fs';
import path from 'node:path';
import { applyRealSchema } from '../e2e/fixtures/sync';

test('activation previews the saved TS connection, refuses stale planning, and retries a failed delivery', async ({ page, request }, testInfo) => {
  test.setTimeout(90_000);
  await page.setViewportSize({ width: 1440, height: 1200 });
  const root = mkdtempSync(path.join(process.env.PSF_GUARD_DIRECTOR_E2E_TMP!, 'ts-activation-'));
  const source = path.join(root, 'TargetScheduler.sqlite');
  const ts = new Database(source);
  applyRealSchema(ts);
  ts.prepare('INSERT INTO exposuretemplate (Id,profileId,name,filtername,gain,offset,bin,readoutmode,guid) VALUES(1,?,?,?,100,30,1,0,?)').run('p', 'Ha', 'Ha', randomUUID());
  ts.prepare("INSERT INTO project (Id,profileId,name,description,state,priority,isMosaic,flatsHandling,guid) VALUES(1,'p','Heart Nebula','',1,1,0,0,?)").run(randomUUID());
  ts.prepare('INSERT INTO target (Id,name,active,ra,dec,epochcode,rotation,projectid,guid) VALUES(1,?,1,2.5466667,61.45,2,0,1,?)').run('Heart Nebula', randomUUID());
  ts.prepare('INSERT INTO exposureplan (Id,profileId,exposure,desired,acquired,accepted,targetid,exposureTemplateId,enabled,guid) VALUES(1,?,300,40,1,1,1,1,1,?)').run('p', randomUUID());
  ts.prepare('INSERT INTO acquiredimage (Id,projectId,targetId,acquireddate,filtername,gradingStatus,metadata,profileId,exposureId,guid) VALUES(1,1,1,1750000000,?,1,?,?,1,?)').run('Ha', JSON.stringify({ FileName: 'heart.fits' }), 'p', randomUUID());
  const slug = `ts-activation-${randomUUID().slice(0, 8)}`;
  try {
    const imported = await request.post('/api/databases/import-ts', { data: { name: 'Observatory rig', slug, db_path: source, image_dirs: [root] } });
    expect(imported.ok()).toBeTruthy();
    await expect.poll(async () => (await (await request.get('/api/databases')).json()).data.some((entry: { id: string }) => entry.id === slug)).toBe(true);
    const catalog = (await (await request.get('/api/databases')).json()).data.find((entry: { id: string }) => entry.id === slug);
    expect((await request.put(`/api/databases/${slug}`, { data: { ts_sync: { ...catalog.ts_sync, writeback: false, on_open: false, on_change: false, interval_minutes: 0 } } })).ok()).toBeTruthy();
    await page.goto('/#/');
    await expect(page.locator('[data-project-key]').filter({ hasText: 'Heart Nebula' })).toHaveCount(1);
    const view = (await (await request.get(`/api/director/v1/catalogs/${slug}/rig/profile`)).json()).data;
    const optics = { sensor_width_px: 6248, sensor_height_px: 4176, pixel_size_um: 3.76, focal_length_mm: 749, aperture_mm: 107, rotation: { mode: 'manual', angle_degrees: 0 } };
    expect((await request.put(`/api/director/v1/catalogs/${slug}/rig/profile`, { data: { expected_revision: view.profile.revision, optics: { value: optics, source: { kind: 'manual' } }, site: null, horizon: null, sky_quality: null, limits: { value: view.profile.limits.value, source: { kind: 'manual' } }, peer_id: null } })).ok()).toBeTruthy();
    await page.reload();
    await page.locator('[data-project-key]').filter({ hasText: 'Heart Nebula' }).getByRole('button', { name: /^Open the .* plan$/ }).first().click();
    await page.getByRole('button', { name: "Add a column on the mosaic's east side" }).click();
    const save = page.getByRole('region', { name: 'Unsaved changes' });
    await save.getByRole('button', { name: 'Save changes' }).click();
    await expect(save).toContainText('All changes saved');
    await page.getByRole('region', { name: 'Needs activating' }).getByRole('button', { name: /^Activate/ }).click();
    const dialog = page.getByRole('dialog', { name: 'Activate on the rigs' });
    const delivery = dialog.getByRole('note', { name: 'Target Scheduler planning delivery' });
    await expect(delivery).toContainText('TargetScheduler.sqlite');
    await expect(delivery).toContainText('Targets: 1 new');
    await expect(dialog.getByRole('status')).toHaveText('Preview ready');
    await dialog.getByText('What changes in Observatory rig', { exact: true }).click();
    await dialog.screenshot({ path: testInfo.outputPath('ts-activation-preview.png') });
    expect((ts.prepare('SELECT count(*) AS n FROM target').get() as { n: number }).n).toBe(1);
    ts.prepare('UPDATE exposureplan SET desired=7 WHERE Id=1').run();
    await dialog.getByRole('button', { name: 'Activate', exact: true }).click();
    await expect(dialog.getByRole('alert').filter({ hasText: 'Changed since the preview' })).toContainText('Target Scheduler connection or planning');
    await expect(dialog.getByRole('status')).toHaveText('Preview ready');
    ts.exec("CREATE TRIGGER refuse_planning BEFORE INSERT ON target BEGIN SELECT RAISE(ABORT,'TS temporarily refuses planning'); END;");
    await dialog.getByRole('button', { name: 'Activate', exact: true }).click();
    await expect(dialog.getByRole('status')).toHaveText('Activated locally; TS delivery pending');
    await expect(dialog.getByRole('note', { name: 'Not sent to Target Scheduler' })).toBeVisible();
    await expect(dialog.getByRole('heading', { name: 'Planned locally; not sent to Target Scheduler' })).toBeVisible();
    await dialog.locator('.dialog-body').evaluate(element => { element.scrollTop = 0; });
    await dialog.screenshot({ path: testInfo.outputPath('ts-activation-pending.png') });
    ts.exec('DROP TRIGGER refuse_planning');
    await dialog.getByRole('button', { name: /^Send to Target Scheduler/ }).click();
    await expect(dialog.getByRole('status')).toHaveText('Activated');
    await expect(dialog.getByRole('heading', { name: 'Target Scheduler now shoots' })).toBeVisible();
    await expect(dialog.getByRole('note', { name: 'Not sent to Target Scheduler' })).toHaveCount(0);
    expect((ts.prepare('SELECT count(*) AS n FROM target').get() as { n: number }).n).toBe(2);
    expect((ts.prepare('SELECT gradingStatus AS grade FROM acquiredimage').get() as { grade: number }).grade).toBe(1);
    expect((ts.prepare('SELECT acquired FROM exposureplan WHERE Id=1').get() as { acquired: number }).acquired).toBe(1);
    await dialog.locator('.dialog-body').evaluate(element => { element.scrollTop = 0; });
    await dialog.screenshot({ path: testInfo.outputPath('ts-activation-delivered.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBeTruthy();
  } finally {
    ts.close();
    await request.delete(`/api/databases/${slug}`);
  }
});
