import * as fs from 'fs';
import * as path from 'path';
import { describe, expect, it } from 'vitest';
import { THEME_ALLOWLIST, type ThemeFindings } from './themeTokens.allowlist';

/**
 * Colours and interaction states come from the tokens in App.css's `:root`
 * (see the Styling section of static/README.md). These checks fail when a
 * stylesheet or a component writes a colour literal or styles a state with a
 * class of its own. The literals and classes kept on purpose are listed in
 * themeTokens.allowlist.ts; that list may only shrink.
 *
 * After removing one on purpose, regenerate the list with
 * `UPDATE_THEME_ALLOWLIST=1 npx vitest run src/__tests__/themeTokens.test.ts`.
 */

const SRC = path.resolve(__dirname, '..');
const ALLOWLIST_FILE = path.join(__dirname, 'themeTokens.allowlist.ts');

function walk(directory: string, out: string[] = []): string[] {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== '__tests__' && entry.name !== '__fixtures__' && entry.name !== 'test') {
        walk(full, out);
      }
    } else {
      out.push(full);
    }
  }
  return out;
}

const files = walk(SRC);
const COLOUR = /#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?)\(/;
// Classes that only say a control's state; ARIA attributes say it instead.
const STATE_CLASS = /\.(active|selected|is-on|is-active|is-selected|is-chosen|is-current|is-open|is-pressed)(?![\w-])/g;

function add(findings: ThemeFindings, file: string, entry: string) {
  const list = (findings[file] ??= []);
  if (!list.includes(entry)) list.push(entry);
}

/** Every leaf block of a stylesheet: its selector and its declarations. */
function rules(text: string): { selector: string; body: string }[] {
  const out: { selector: string; body: string }[] = [];
  for (const match of text.matchAll(/([^{}]*)\{([^{}]*)\}/g)) {
    out.push({ selector: match[1].trim().replace(/\s+/g, ' '), body: match[2] });
  }
  return out;
}

function scan() {
  const colours: ThemeFindings = {};
  const states: ThemeFindings = {};
  const quotes: string[] = [];
  const inline: ThemeFindings = {};
  for (const file of files) {
    const name = path.relative(SRC, file).split(path.sep).join('/');
    if (file.endsWith('.css')) {
      const text = fs.readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
      for (const { selector, body } of rules(text)) {
        for (const declaration of body.split(';')) {
          const at = declaration.indexOf(':');
          if (at < 0) continue;
          const property = declaration.slice(0, at).trim();
          const value = declaration.slice(at + 1).trim().replace(/\s+/g, ' ');
          // Defining a token is where a colour belongs.
          if (property.startsWith('--')) continue;
          if (COLOUR.test(value)) add(colours, name, `${property}: ${value}`);
        }
        for (const [state] of selector.matchAll(STATE_CLASS)) add(states, name, `${selector} (${state})`);
        if (/\[aria-[a-z]+="/.test(selector)) quotes.push(`${name}: ${selector}`);
      }
    } else if (/\.(ts|tsx)$/.test(file) && !/\.test\.tsx?$/.test(file)) {
      const text = fs.readFileSync(file, 'utf8');
      // Only a colour inside a string literal is drawn; comments cite issues.
      for (const literal of text.match(/'(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*"|`(?:[^`\\]|\\.)*`/g) ?? []) {
        if (COLOUR.test(literal)) add(inline, name, literal.replace(/\s+/g, ' '));
      }
    }
  }
  return { colours, states, quotes, inline };
}

function minus(found: ThemeFindings, allowed: ThemeFindings): string[] {
  const out: string[] = [];
  for (const [file, entries] of Object.entries(found)) {
    for (const entry of entries) if (!allowed[file]?.includes(entry)) out.push(`${file}: ${entry}`);
  }
  return out.sort();
}

function sorted(findings: ThemeFindings): ThemeFindings {
  return Object.fromEntries(
    Object.keys(findings).sort().map((file) => [file, [...findings[file]].sort()]),
  );
}

const found = scan();

if (process.env.UPDATE_THEME_ALLOWLIST) {
  const body = JSON.stringify(
    { colours: sorted(found.colours), states: sorted(found.states), inline: sorted(found.inline) },
    null,
    2,
  );
  fs.writeFileSync(
    ALLOWLIST_FILE,
    `/**
 * Colour literals and state classes kept on purpose, by file. Generated by
 * themeTokens.test.ts; see there. Each one should have a reason: a palette
 * that is data, a one-off mark on a chart, a canvas that cannot read CSS
 * variables, or a state no ARIA attribute describes.
 */

export type ThemeFindings = Record<string, string[]>;

export const THEME_ALLOWLIST: { colours: ThemeFindings; states: ThemeFindings; inline: ThemeFindings } = ${body};
`,
  );
}

describe('theme tokens', () => {
  it('stylesheets write no colour outside a token definition', () => {
    expect(minus(found.colours, THEME_ALLOWLIST.colours), 'use a token from App.css :root').toEqual([]);
  });

  it('components write no colour in their source', () => {
    expect(minus(found.inline, THEME_ALLOWLIST.inline), 'use var(--…) with a token').toEqual([]);
  });

  it('states come from ARIA attributes, not classes of their own', () => {
    expect(minus(found.states, THEME_ALLOWLIST.states), 'style the ARIA attribute instead').toEqual([]);
  });

  it('attribute selectors use single quotes', () => {
    expect(found.quotes).toEqual([]);
  });

  it('keeps the allowlist to what is still there', () => {
    const stale = [
      ...minus(THEME_ALLOWLIST.colours, found.colours),
      ...minus(THEME_ALLOWLIST.inline, found.inline),
      ...minus(THEME_ALLOWLIST.states, found.states),
    ];
    expect(stale, 'remove these from themeTokens.allowlist.ts').toEqual([]);
  });
});
